#!/bin/bash
# Concatenate Stage 5 modules into a single main.dm for bootstrap compilation
# Usage: cd stage5 && bash gen_bootstrap.sh

set -e

OUTPUT="main.dm"

# Embed the dAImond runtime sources (runtime/*.dm) in the compiler as one
# string, so compiled programs need no runtime files on disk
RUNTIME_SOURCES="runtime/string.dm runtime/convert.dm runtime/map.dm"
{
    echo "module prelude"
    echo ""
    echo "-- Generated by gen_bootstrap.sh from $RUNTIME_SOURCES; edit those files instead."
    echo "-- The compiler parses this source into every program it compiles."
    echo ""
    printf 'fn prelude_source() -> string {\n    return "'
    cat $RUNTIME_SOURCES | sed '/^module /d' | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' | awk '{ printf "%s\\n", $0 }'
    printf '"\n}\n'
} > prelude.dm

# Order matters: dependencies before dependents
cat \
    token.dm \
    lexer.dm \
    ast.dm \
    ir.dm \
    ir_builder.dm \
    llvm.dm \
    parser.dm \
    ir_gen.dm \
    ir_gen_decl.dm \
    ir_gen_stmt.dm \
    ir_gen_expr.dm \
    ir_gen_builtins.dm \
    ir_gen_comptime.dm \
    llvm_gen.dm \
    llvm_gen_call.dm \
    llvm_gen_simd.dm \
    prelude.dm \
    main_split.dm \
| sed '/^module /d' | sed '/^import /d' > "$OUTPUT"

# Add module declaration at the top
sed -i '1i module main' "$OUTPUT"

echo "Generated $OUTPUT"
wc -l "$OUTPUT"
